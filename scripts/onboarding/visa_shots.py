import os, sys
from playwright.sync_api import sync_playwright
B="http://127.0.0.1:8111"; IMG=os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "docs", "onboarding", "img")
with sync_playwright() as p:
    b=p.chromium.launch(); pg=b.new_page(viewport={"width":1366,"height":900})
    pg.goto(B+"/admin/login"); pg.fill("input[name=login]","medina"); pg.fill("input[name=password]","demo")
    pg.click("button[type=submit]"); pg.wait_for_load_state("networkidle")
    pg.goto(B+"/admin"); pg.wait_for_load_state("networkidle"); pg.wait_for_timeout(600)
    pg.locator("[data-attention] .card, .inbox-list .card", has_text="Бакыт С.").first.click()
