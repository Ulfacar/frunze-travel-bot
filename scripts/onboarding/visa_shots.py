    v=pg.locator("details.chat-visa")
    print("visa block count", v.count())
    pg.screenshot(path=os.path.join(IMG,"05a-vizy-svernuto.png"))
    v.locator("summary").click(); pg.wait_for_timeout(400)
    f=pg.locator("details.chat-visa form")
    f.locator("select[name=citizenship]").select_option(index=1)
    f.locator("input[name=country]").fill("Германия")
    f.locator("select[name=visa_type]").select_option("tourist")
    f.locator("input[name=travel_dates]").fill("июнь 2027, 10 дней")
    pg.wait_for_timeout(4800)   # пережить один опрос чата: набранное должно остаться
    print("after poll country =", f.locator("input[name=country]").input_value())
    f.locator("input[name=cost]").fill("250"); f.locator("select[name=cost_currency]").select_option(index=1)
    pg.screenshot(path=os.path.join(IMG,"05b-vizy-zapolnenie.png"))
    f.locator("button[type=submit]").click(); pg.wait_for_load_state("networkidle"); pg.wait_for_timeout(900)
    print("summary:", pg.locator("details.chat-visa summary").inner_text())
    pg.screenshot(path=os.path.join(IMG,"05c-vizy-sohraneno.png"))
    m=b.new_page(viewport={"width":390,"height":844})
    m.goto(B+"/admin/login"); m.fill("input[name=login]","medina"); m.fill("input[name=password]","demo"); m.click("button[type=submit]")
    m.wait_for_load_state("networkidle"); m.goto(B+"/admin"); m.wait_for_load_state("networkidle"); m.wait_for_timeout(600)
