def _font(run, size, bold=False, color=None, italic=False):
    run.font.name = "Calibri"
    run.font.size = Pt(size)
    run.font.bold = bold
    run.font.italic = italic
    if color is not None:
        run.font.color.rgb = color


def h1(doc, text):
    p = doc.add_paragraph()
    p.paragraph_format.space_before = Pt(0)
    p.paragraph_format.space_after = Pt(4)
    _font(p.add_run(text), 22, bold=True, color=NAVY)
    return p


def h2(doc, text):
    p = doc.add_paragraph()
    p.paragraph_format.space_before = Pt(16)
    p.paragraph_format.space_after = Pt(6)
    _font(p.add_run(text), 13, bold=True, color=TEAL)
    return p


def para(doc, text, size=11, color=None, italic=False, after=6):
    p = doc.add_paragraph()
    p.paragraph_format.space_after = Pt(after)
    _font(p.add_run(text), size, color=color, italic=italic)
    return p


def question(doc, num, text, hint=""):
    p = doc.add_paragraph()
    p.paragraph_format.space_after = Pt(2)
    p.paragraph_format.left_indent = Pt(14)
    _font(p.add_run(f"{num}. "), 11, bold=True, color=NAVY)
    _font(p.add_run(text), 11)
    if hint:
        ph = doc.add_paragraph()
        ph.paragraph_format.space_after = Pt(8)
        ph.paragraph_format.left_indent = Pt(28)
        _font(ph.add_run(hint), 10, color=GREY, italic=True)
    else:
        p.paragraph_format.space_after = Pt(8)


