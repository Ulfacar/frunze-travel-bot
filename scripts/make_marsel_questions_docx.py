def build() -> Path:
    doc = Document()
    section = doc.sections[0]
    section.left_margin = section.right_margin = Pt(54)

    h1(doc, "Бот и база кандидатов — вопросы Марселю")
    para(doc, "Frunze Travel · 14 августа 2026", 10, color=GREY, after=14)

    para(doc,
         "Марсель, мы начинаем делать для вас отдельного бота: он будет первым отвечать "
         "людям в WhatsApp, расспрашивать их и складывать каждого в вашу базу кандидатов. "
         "База будет в вашей личной панели — заходите под своим логином и смотрите список "
         "с поиском по стране, профессии и стажу. Чужих клиентов там не будет, ваших "
         "не увидит никто, кроме вас.", 11)
    para(doc,
         "Чтобы бот спрашивал то, что нужно именно вам, ответьте, пожалуйста, на вопросы "
         "ниже. Отвечать можно как удобно: голосовыми по номерам, текстом или списком. "
         "Если на какой-то вопрос ответа пока нет — так и скажите, это тоже ответ.", 11,
         after=4)
    para(doc,
         "Отдельно готовить ничего не нужно: списка работодателей и справочника профессий "
         "мы не ждём — соберём их сами по реальным обращениям за первую неделю.",
         10, color=SLATE, italic=True, after=14)

    num = 1
    for title, items in BLOCKS:
        h2(doc, title)
        for text, hint in items:
            question(doc, num, text, hint)
            num += 1

    h2(doc, "Что будет дальше")
    para(doc,
         "Как получим ответы — соберём из них точное описание работы бота и покажем вам "
         "на согласование до того, как начнём делать. Первым запустим сбор кандидатов, "
         "следом — экран базы с поиском и выгрузкой.", 11)

    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    p.paragraph_format.space_before = Pt(20)
    _font(p.add_run("Frunze Travel"), 9, color=GREY)

    OUT.parent.mkdir(parents=True, exist_ok=True)
    doc.save(OUT)
    return OUT


if __name__ == "__main__":
    print(f"готово: {build()}")
