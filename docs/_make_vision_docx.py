"""Генерирует Word: «Как будет работать бот — на подтверждение клиенту»."""
import os
from docx import Document
from docx.shared import Pt, RGBColor

OUT = os.path.join(os.path.dirname(__file__), "Бот Frunze Travel — на подтверждение (финал).docx")

doc = Document()
style = doc.styles["Normal"]
style.font.name = "Calibri"
style.font.size = Pt(11)

BLUE = RGBColor(0x1F, 0x4E, 0x79)
GREY = RGBColor(0x66, 0x66, 0x66)
GREEN = RGBColor(0x2E, 0x7D, 0x32)


def h1(text):
    p = doc.add_heading(text, level=1)
    for r in p.runs:
        r.font.color.rgb = BLUE


def h2(text):
    p = doc.add_heading(text, level=2)
    for r in p.runs:
        r.font.color.rgb = BLUE


def para(text="", italic=False, bold=False, color=None, size=None):
    p = doc.add_paragraph()
    r = p.add_run(text)
    r.italic, r.bold = italic, bold
    if color:
        r.font.color.rgb = color
    if size:
        r.font.size = Pt(size)
    return p


def step(text):
    doc.add_paragraph(text, style="List Number")


def bullet(text):
    doc.add_paragraph(text, style="List Bullet")


def how_we_see(text):
    p = doc.add_paragraph()
    r = p.add_run("Как мы предлагаем: ")
    r.bold = True
    r.font.color.rgb = GREEN
    p.add_run(text)


def confirm(question):
    p = doc.add_paragraph()
    r = p.add_run("✔ Подтвердите / поправьте: ")
    r.bold = True
    p.add_run(question)
    a = doc.add_paragraph()
    ar = a.add_run("Ответ: ")
    ar.font.color.rgb = GREY
    a.add_run("_" * 55)
    doc.add_paragraph()


