"""ГЕЙТ: бот не утверждает, откуда куда летает. Это знает только поиск.

Написан ДО правки.

## Замер на боевом TourVisor 11.09.2026

В `branding.FRUNZE_DESTINATIONS` было записано как факт:

    «Из Бишкека сейчас: Египет, Турция, Дубай/ОАЭ.
     Из Алматы: Мальдивы, Маврикий, Грузия, Вьетнам, Сингапур, Япония и др.»

Живой поиск показал, что список врёт про два направления из шести:

    Вьетнам, Фукуок, вылет Бишкек   → 25 отелей, БЕЗ пересадки, от 1738 USD (Anex)
    Мальдивы,        вылет Бишкек   → 25 отелей, БЕЗ пересадки
    Грузия / Сингапур / Таиланд     → действительно только через Алматы

Цена ошибки: клиенты спрашивали Вьетнам в 145 диалогах, бот 62 раза отправил их в
Алматы, а менеджеры руками отправили 40 карточек «Бишкек → Вьетнам». В одном диалоге
менеджер извиняется перед клиентом: «наш бот оказывается неправильно ответил».

## Правило

Список направлений по городам вылета не хранится в тексте вообще. Любой такой список
протухает — этот протух за полтора месяца, а бот произносил его как факт и уверенно
отговаривал клиента от товара, который мы продаём.

Откуда куда летает, знает поиск: `search_detailed` сам проверяет Бишкек и сам
подставляет Алматы, если из Бишкека пусто (`client.py`, `fallback_departure`).
"""
from __future__ import annotations

import pytest

from app.core.branding import FRUNZE_DESTINATIONS


FALSE_CLAIMS = ("вьетнам", "мальдив")


@pytest.mark.parametrize("word", FALSE_CLAIMS)
def test_no_claim_that_destination_needs_almaty(word):
    """Про Вьетнам и Мальдивы нельзя говорить «только из Алматы» — это неправда."""
    low = FRUNZE_DESTINATIONS.lower()
    if word not in low:
        return                      # направление не упомянуто — утверждать нечего
    tail = low.split(word, 1)[0]
    assert "из алматы:" not in tail, (
        f"«{word}» перечислено после «Из Алматы:» — проверено живым поиском, "
        f"оно летает из Бишкека напрямую")


def test_no_hard_list_of_cities_per_destination():
    """Текст не раскладывает направления по городам вылета — этот список протухает."""
    low = FRUNZE_DESTINATIONS.lower()
    assert not ("из бишкека сейчас" in low and "из алматы:" in low), (
        "жёсткая раскладка «из Бишкека то, из Алматы это» вернулась в текст")


def test_still_tells_the_client_what_we_sell():
    """Ложноположительный: убрав неправду, нельзя оставить пустоту.

    Константа идёт в готовый ответ FAQ «По турам работаем с такими направлениями»,
    поэтому она обязана оставаться осмысленной для клиента.
    """
    assert len(FRUNZE_DESTINATIONS) > 40
    low = FRUNZE_DESTINATIONS.lower()
    assert "турци" in low, "самое massовое направление должно быть названо"


def test_mentions_that_availability_is_checked_by_search():
    """Вместо утверждения о географии — честное «уточняется поиском»."""
    low = FRUNZE_DESTINATIONS.lower()
    assert any(w in low for w in ("подбер", "уточн", "проверя", "покаж")), FRUNZE_DESTINATIONS
