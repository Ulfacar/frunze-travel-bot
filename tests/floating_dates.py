"""Сроки для тестовых фикстур — от сегодняшнего дня, а не календарные.

Разбор 27.11.2026 (docs/test-debt-2026-11-27.md): фикстуры знаний держали срок
пересмотра правил «2026-12-01». С 01.12.2026 он истёк бы, и тесты публикации,
решений и квалификации упали бы без единого дефекта в коде. Срок «через год от
сегодня» сохраняет смысл фикстуры — «правило действует» — в любой день.
"""
from datetime import date, timedelta

FAR = date.today() + timedelta(days=365)
FAR_DAY = FAR.isoformat()                 # для полей-дат: review_due_on, effective_from
FAR_DUE = f"{FAR_DAY}T00:00:00Z"          # для полей-моментов: review_due_at
