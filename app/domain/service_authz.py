"""E1-02: кто и что может делать с услугой (ServiceCase).

Отдельный модуль чистых правил — как `app/domain/permissions.py` для диалогов.
Ни БД, ни сессии, ни HTTP: только `Actor` и факты об объекте. Благодаря этому
правило можно проверить в тесте одной строкой и переиспользовать из любого места.

Зачем отдельно от `permissions.py`. Там правила про переписку: кто видит диалог и
кто вправе написать клиенту. Здесь — про коммерческую услугу: кто заводит договор,
кто двигает этап, кто настраивает продукты. Объекты разные, и смешивать их в одном
наборе функций значит однажды разрешить менеджеру лишнее, перепутав assignment с
владением услугой.

**Главное требование — AC-33 из ТЗ:** прямой запрос чужого направления и финансового
исправления без прав получает отказ НА СЕРВЕРЕ, независимо от интерфейса. Поэтому
проверки живут в доменном слое и вызываются из операций, а не из роутера: спрятанная
кнопка защитой не считается.

Правило проекта, которое здесь сохранено: **полный администратор не получает
автоматического права действовать за менеджера.** В `permissions.can_send` это уже
так — админ видит диалог, но писать клиенту может только владелец. Для услуг так же:
админ видит и настраивает, но ведёт услугу тот, за кем она закреплена.
"""
from __future__ import annotations

from app.domain.models import DomainError
from app.domain.permissions import Actor


def _direction_allowed(actor: Actor, direction: str | None) -> bool:
    """Покрывает ли скоуп менеджера это направление.

    `None` — это НЕ «разрешено всем». Проверяющая модель нашла здесь дыру: когда
    продукт услуги не найден, направление приходит как None, и менеджер без единого
    направления получал доступ. Неизвестное направление приравнено к чужому: его
    проходит только полный администратор.
    """
    if actor.is_full_admin:
        return True
    if direction is None:
        return False
    return direction in actor.allowed_directions


def _is_owner(actor: Actor, owner_login: str | None) -> bool:
    """Закреплена ли услуга за этим менеджером. Сравниваем логины в нижнем
    регистре: `actor_for` уже нормализует, но услуга могла быть заведена кодом."""
    owner = str(owner_login or "").strip().lower()
    me = str(actor.manager_id or "").strip().lower()
    # Нормализуем ДО проверки пустоты: строка из пробелов истинна, и прежний порядок
    # приравнивал пустого актора к владельцу «   ». Пустой логин не владеет ничем.
    if not owner or not me:
        return False
    return owner == me


def can_view_case(actor: Actor, *, direction: str | None, owner_login: str | None) -> bool:
    """Видеть услугу: полный администратор — любую, менеджер — свою в своём направлении.

    Чужая услуга внутри своего направления не видна: направление это команда, а не
    общий доступ. Для разбора спорных случаев есть администратор.
    """
    if actor.is_full_admin:
        return True
    return _direction_allowed(actor, direction) and _is_owner(actor, owner_login)


def can_open_case(actor: Actor, *, direction: str | None) -> bool:
    """Завести услугу (подписан договор) может менеджер своего направления.

    Администратору это тоже доступно: он может оформить договор за отсутствующего
    менеджера — в отличие от отправки сообщения клиенту, где подмена автора недопустима.
    """
    return _direction_allowed(actor, direction)


def can_advance_case(actor: Actor, *, direction: str | None, owner_login: str | None) -> bool:
    """Двигать этап услуги вправе только тот, за кем она закреплена.

    Администратор НЕ получает это автоматически — ровно как с отправкой сообщения
    (`permissions.can_send`). Переход этапа это утверждение факта («бронь подтверждена»,
    «документы переданы»), и отвечать за него должен тот, кто ведёт клиента. Нужно
    вмешаться — сначала переназначить услугу на себя, и это останется в истории.
    """
    return _direction_allowed(actor, direction) and _is_owner(actor, owner_login)


def can_reassign_case(actor: Actor, *, direction: str | None, owner_login: str | None,
                      target_login: str) -> bool:
    """Переназначить услугу.

    Логика повторяет `permissions.can_reassign`, чтобы не разошлись два правила:
    администратор может всё; менеджер может взять ничью услугу или подтвердить
    текущего владельца, но отобрать услугу у другого менеджера — полномочие
    администратора.
    """
    if actor.is_full_admin:
        return True
    if not _direction_allowed(actor, direction):
        return False
    if not owner_login:
        return True
    if str(owner_login).strip().lower() == str(target_login).strip().lower():
        return True
    return False


def can_manage_products(actor: Actor) -> bool:
    """Заводить продукты, публиковать версии процессов и архивировать — только
    полный администратор.

    По ТЗ (раздел 4) настройка продуктов и правил — полномочие руководителя, а не
    рядового менеджера. Опубликованная версия процесса определяет, как пойдут все
    будущие услуги продукта, и цена ошибки здесь выше одной карточки.
    """
    return actor.is_full_admin


def can_correct_money(actor: Actor, *, direction: str | None = None) -> bool:
    """Финансовое исправление (правка подтверждённой суммы, возврат, аннулирование).

    По ТЗ (раздел 4 и MONEY-05) это полномочие руководителя с причиной и аудитом.
    Состав расширенных прав — нерешённый вопрос DEC-11, поэтому доступ закрыт всем,
    кроме полного администратора.

    Направление проверяется дополнительно, и вот почему: в одной системе живут два
    РАЗНЫХ бизнеса с разными владельцами — туры (Frunze Travel) и визы (GetVisa).
    Без этой проверки администратор одного бизнеса мог исправить сумму договора и
    провести возврат в другом. Финансовый аудит нашёл это как открытый риск.
    Админ с пустым списком направлений считается владельцем системы и не ограничен
    (так заведены служебные акторы и переносы данных).

    Сузить право позже нельзя безболезненно, а расширить — одна строка: поэтому по
    умолчанию берём более строгий вариант. Решение 05.10, отменяется Аланом.
    """
    if not actor.is_full_admin:
        return False
    if direction is None or not actor.allowed_directions:
        return True
    return direction in actor.allowed_directions


class PermissionDenied(DomainError):
    """Отказ по правам, отличимый от ошибки данных.

    Нужен отдельный тип, потому что ТЗ (раздел 13.1) требует разных ответов: нет
    прав — 403 либо нераскрывающий существование 404 по единой политике, а
    некорректные данные — 422. Один `DomainError` на всё заставил бы роутер гадать
    по тексту сообщения.
    """


# Явный актор для служебных вызовов: сидеры, миграции данных, фоновые джобы.
# Сделан видимым, а не «права не переданы — значит можно»: молчаливый обход
# однажды окажется в обычной операции, и AC-33 перестанет держать.
SYSTEM_ACTOR = Actor(manager_id="system", is_full_admin=True)


def require(allowed: bool, what: str) -> None:
    """Короткий гейт: `require(can_advance_case(...), "advance case")`.

    Сообщение намеренно не содержит ни логина, ни идентификаторов объекта: по ТЗ
    аудит и ответы об отказе не раскрывают персональные данные.
    """
    if not allowed:
        raise PermissionDenied(f"not allowed: {what}")
