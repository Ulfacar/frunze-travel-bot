# -*- coding: utf-8 -*-
"""Автоматический перевод лида «Новый лид» → «В работе».

Правка Медины 12.11.2026, уточнение к её ответам по воронкам:

    «Думаю, удобнее будет сделать комбинированный вариант. Например, когда менеджер
    начинает общение с клиентом, система может автоматически переводить его из
    „Новый лид“ во „В работе“. А остальные стадии менеджер уже будет менять
    самостоятельно, в зависимости от ситуации.»

То есть автоматика ровно одна и в одном месте. Всё остальное движение по доске
остаётся за менеджером — это её прямое условие, и расширять автоматику «заодно»
нельзя.

## Почему признак — сообщение менеджера

«Менеджер начал общение» в нашей базе видно по сообщению с отправителем `manager`.
Оно попадает туда тремя путями: отправка из панели, зеркало ответа из WhatsApp и
зеркало из Битрикса. Последние два важнее всего: замер 12.11.2026 показал, что в
панели за ноябрь десять рабочих действий, а сообщений менеджеров 2530 — люди пишут
клиентам не из панели. Если ловить только отправку из панели, правка почти ничего не
сделает.

## Чего функция НЕ делает

Не двигает ничего, кроме «Новый лид». Лид в «Консультации» или «Записан в офис»
останется где стоит, даже если менеджер написал снова: иначе автоматика откатывала бы
карточку назад и отбирала у менеджера его же работу.

Не трогает туры: колонки по направлениям разные, у туров свой набор, и её правка про
визы. Список направлений вынесен в настройку, а не зашит.

Замер на проде 12.11.2026 перед включением: визовых в «Новый лид» 2239, из них
менеджер уже писал 1279 — столько карточек переедет. Активных среди них за 30 дней
220, остальное старое. Поэтому перевод СТАРЫХ карточек сделан отдельной командой с
показом, а здесь только поведение вперёд.
"""
from __future__ import annotations

# Ключи стадий, а не подписи: подписи колонок меняются (её набор — «Новый лид»,
# «В работе»), а машина состояний работает на ключах.
STAGE_NEW_LEAD = "greeting"
STAGE_IN_WORK = "qualification"


def stage_after_manager_message(funnel: str | None, stage: str | None,
                                funnels: tuple[str, ...] | list[str]) -> str | None:
    """Новая стадия, если сообщение менеджера её меняет. Иначе None.

    `None` означает «не трогать» — именно так и вызывается: сравнение с None, а не
    с пустой строкой, чтобы случайная пустая стадия не превратилась в запись.
    """
    if (funnel or "") not in tuple(funnels or ()):
        return None
    if (stage or "") != STAGE_NEW_LEAD:
        return None
    return STAGE_IN_WORK
