# выездное вето, — ровно как сильному маркеру в v1.
#
# `\b` перед предлогом обязателен. Без него «документо**в кыргыз**станцам на шенген»
# совпадало с `в\s+кыргыз`: последняя буква слова «документов» принималась за предлог
