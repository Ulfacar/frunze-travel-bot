# 28.10 запуском, не рассуждением.
#
# Кыргызского локатива «кыргызстанда» здесь НЕТ: это «в Кыргызстане», то есть место, а
# не направление. «Кыргызстанда жашайм, АКШга виза керек» — «живу в Кыргызстане, нужна
