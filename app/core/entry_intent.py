# Длинные основы проверяем первыми: в Python альтернатива `|` отдаёт первое совпадение,
# и «казах» иначе перекрыл бы «казашк» на ровном месте.
_NATIONALITY_ALT = "|".join(
    re.escape(stem) for stem in sorted(_NATIONALITY, key=len, reverse=True))

# Нужно именно САМОНАЗВАНИЕ. «Виза для узбеков» — это не заявление о своём гражданстве,
# а вопрос про третьих лиц, и забирать по нему диалог нельзя.
#
# Отрицание `(?!\s*язык)` стоит не для красоты: «я русский язык плохо знаю» — реплика
# кыргызскоязычного клиента, и считать его гражданином России по ней нельзя.
_NATIONALITY_CLAIM = re.compile(
    rf"(?:^|[\s.,;:!?()«»\"'—–-])(?:я|мы)\s*(?:[—–-]\s*)?"
    rf"(?P<self>{_NATIONALITY_ALT})\w{{0,6}}\b(?!\s*язык)"
    rf"|\b(?P<by>{_NATIONALITY_ALT})\w{{0,6}}\s+по\s+национальност",
    re.IGNORECASE)


def _nationality_origins(low: str) -> list[str]:
    """Гражданства, названные о себе национальностью: «я узбек» → UZB."""
    out: list[str] = []
    for match in _NATIONALITY_CLAIM.finditer(low):
        word = (match.group("self") or match.group("by") or "").lower()
        iso = _NATIONALITY.get(word)
        if iso:
            out.append(iso)
    return out


def _claimed_origins_v2(low: str) -> list[str]:
    """Все свои гражданства: и «я из Узбекистана», и «я узбек»."""
    return _claimed_origins(low) + _nationality_origins(low)


def _without_origin_v2(low: str) -> str:
    """Текст без своего гражданства в обеих формах.

    Зачем убирать и национальность. Основы выездных стран берутся из брендинга, и
    «испан» в них есть: без этой вырезки «я испанец, хочу приехать на 30 дней» ловилось
    выездным вето по слову «испанец» и уезжало в воронку для граждан КР. Та же вырезка
    снимает ложный вопрос о направлении у своего гражданина: «я кыргыз, нужна виза» —
    страна упомянута только как национальность, спрашивать «в Кыргызстан или из
    Кыргызстана?» не о чем.
    """
    return _NATIONALITY_CLAIM.sub(" ", _without_origin(low))


def _kg_mentioned(low: str) -> bool:
    return any(stem in low for stem in _KG_STEM)


def _detect_v2_direction(low: str) -> Intent | None:
    """Только ОДНОЗНАЧНОЕ направление «в Кыргызстан». Проверяется ДО выездного вето.

    Эта группа одна имеет право перебить вето — ровно как сильный маркер в v1, и по той
    же причине: «я из Австрии, нужна виза в Кыргызстан» называет Австрию как своё
    гражданство, а не как пункт назначения.

    Про `_without_origin`. Страну, которой клиент назвал СВОЁ гражданство, убираем до
    проверок. Иначе «Я гражданка Кыргызстана, нужна виза в Польшу» попадает во въездную
    ветку: рядом стоят «Кыргызстана» и «виза». Это худший из возможных промахов —
    гражданка КР получает сценарий для иностранца. Поймано тестом.
    """
    return "kg_entry" if _KG_TO.search(_without_origin_v2(low)) else None


def _detect_v2_context(low: str) -> Intent | None:
    """Косвенные признаки v2. Проверяются ПОСЛЕ выездного вето.

    Почему после. Первая версия ставила все правила v2 перед вето, и явный выездной
    запрос их не перебивал: «Нужен шенген, вылет из Кыргызстана» давало вопрос про
    направление, «Я прилетел в Бишкек и хочу шенген» — въездную ветку. Выездной поток
    работает и приносит деньги; забрать его — самая дорогая из возможных ошибок.
    Найдено независимым ревью 28.10, воспроизведено запуском.

    Порядок внутри: кыргызский документ, затем направление «отсюда», затем туры и
    билеты, затем места, и лишь в конце — простое упоминание страны.
    """
    body = _without_origin_v2(low)
    arrival = any(w in low for w in _ARRIVAL_V2)
    foreign = any(iso != "KGZ" for iso in _claimed_origins_v2(low))
    staying = any(w in low for w in _STAY_IN_KG)

    if _KG_IN.search(body):
        return "kg_entry"

    if _KG_DOC.search(body) and not _KG_FROM.search(body):
        return "kg_entry"

    # «Выдворили ИЗ Кыргызстана, хочу снова приехать» — направление назад, но человек
    # едет сюда; то же с просрочкой («как выехать», `_STAY_IN_KG`). Без признака
    # приезда и без признака пребывания «из Кыргызстана» — это отъезд, и ветка
    # выездная. Прежде здесь возвращался вопрос про направление, и «Нужен шенген, вылет
    # из Кыргызстана» получал уточнение вместо работы.
    if _KG_FROM.search(body):
        return "kg_entry" if (arrival or staying) else "outbound"

    if any(w in low for w in _TOURS_TICKETS):
        return None                      # туры и билеты — не въездная ветка

    if any(w in low for w in _PLACE_IN_KG):
        return "kg_entry" if (arrival or staying or foreign) else None

    # Локатив — это место. Если страна упомянута ТОЛЬКО так, спрашивать не о чем:
    # человек говорит, где он живёт, а не куда едет.
    if _KG_LOCATIVE.search(body) and not _kg_mentioned(_KG_LOCATIVE.sub(" ", body)):
        return None

    if _kg_mentioned(body):
        # Страна названа, направления нет и документа нет — спрашиваем, а не угадываем.
        return "ambiguous"
    return None


def detect(text: str, *, sticky: str | None = None,
           routing_v2: bool = False) -> Intent:
    """Тема реплики. `sticky` — уже определённый режим диалога, он сильнее текста.

    `routing_v2` — флаг `kg_entry_routing_v2_enabled`. Передаётся параметром, а не
    читается здесь: функция чистая и синхронная, её гоняют тесты и прогон историй, а
    флаги асинхронные. При `False` поведение дословно прежнее — это проверяется тестом
    на всём наборе реплик, а не на слово.
    """
    low = (text or "").lower()

    if sticky in ("kg_entry", "outbound"):
        # Липкость не должна запирать диалог в неверной ветке: режим мог быть угадан
        # по косвенным признакам. Прямая улика выездного её перебивает — но только
        # прямая, иначе обычное продолжение въездного разговора будет перескакивать.
        if sticky == "kg_entry" and low.strip() and _outbound_evidence(
                low, routing_v2=routing_v2):
            return "outbound"
        return sticky                                  # type: ignore[return-value]

    if not low.strip():
        return "unknown"

    if routing_v2:
        # Те же маркеры, но по границе слова — см. `_ENTRY_STRONG_BOUNDED`.
        if any(rx.search(low) for rx in _ENTRY_STRONG_BOUNDED):
            return "kg_entry"
    elif any(w in low for w in _ENTRY_STRONG):
        return "kg_entry"

    if routing_v2:
        decided = _detect_v2_direction(low)
        if decided is not None:
            return decided

    # Вето считаем по тексту БЕЗ своего гражданства, иначе «я из Германии, хочу
    # приехать туристом» уезжает в выездную воронку из-за слова «Германии».
    #
    # v2: «выезжал» перестаёт перебивать «въезжал» в одной реплике. Иностранец,
    # перечисляющий свои въезды и выезды («въезжал 15 августа, выезжал на неделю»),
    # считался уезжающим и терял ветку — проверено в боевом контейнере 28.10.
    leaving = any(word in low for word in _DEPARTURE)
    if routing_v2 and leaving and any(word in low for word in _ARRIVAL_V2):
        leaving = False

    veto = _without_origin_v2(low) if routing_v2 else _without_origin(low)
    if any(w in veto for w in _OUTBOUND_WORDS) or any(w in veto for w in _OUTBOUND_SHORT):
        return "outbound"
    if any(stem in veto for stem in _outbound_stems()):
        return "outbound"

    # Косвенные правила v2 — только здесь, когда выездное вето уже промолчало.
    if routing_v2:
        decided = _detect_v2_context(low)
        if decided is not None:
            return decided

    # Назвал чужое гражданство — дальше смотрим, куда он собрался. Гражданин КР так
    # про себя не пишет, а его собственное гражданство чужим не считается.
    origins = _claimed_origins_v2(low) if routing_v2 else _claimed_origins(low)
    foreign = any(iso != "KGZ" for iso in origins)
    if foreign and not leaving:
        arrival = _ARRIVAL_V2 if routing_v2 else _ARRIVAL
        if any(word in low for word in arrival):
            return "kg_entry"
        # Просит визу и не назвал ни одной страны (вето выше молчало) — речь о
        # Кыргызстане. Иначе иностранец, написавший «оформите мне визу», уходил в
        # выездную воронку, и бот спрашивал, какую страну он рассматривает.
        if any(word in low for word in _VISA_WORDS_RU) or (
                looks_english(low) and any(re.search(rf"\b{w}\b", low)
                                           for w in _VISA_WORDS_EN)):
            return "kg_entry"

    # Слабый маркер не работает, если клиент прямо говорит об отъезде отсюда:
    # «живу в Бишкеке, хочу выехать на учёбу» — это выездной клиент.
    #
    # v2: «Бишкек» из слабых маркеров убран — он место, а не направление, и один
    # забирал во въездную ветку запрос билетов (живой случай с прода 26.10). В v2
    # места разбираются в `_detect_v2` и требуют спутника.
    weak = (tuple(w for w in _ENTRY_WEAK if w not in _PLACE_IN_KG) if routing_v2
            else _ENTRY_WEAK)
    if any(w in low for w in weak) and not leaving:
        return "kg_entry"

    # Клиентура выездного GetVisa — граждане КР, они пишут по-русски. Англоязычный
    # визовый вопрос без единой выездной страны почти наверняка про въезд. «Почти» —
    # поэтому только после вето выше.
    if looks_english(low) and any(re.search(rf"\b{w}\b", low) for w in _VISA_WORDS_EN):
        return "kg_entry"

    # v2, последним: клиент назвал СВОЁ иностранное гражданство, выездное вето молчит,
    # направления в тексте нет. «Я из Ирака. Куда прислать скан паспорта?» — спрашивать
    # честнее, чем угадывать: иностранец, живущий в Бишкеке, бывает и выездным клиентом.
    #
    # Правило стоит ЗДЕСЬ, а не в `_detect_v2`, именно поэтому: «я из Германии, нужна
    # виза в Польшу» обязана остаться выездной, а вето считается выше.
    if routing_v2 and foreign:
        return "ambiguous"

    return "unknown"
