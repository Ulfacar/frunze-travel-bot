"""График работы офиса — правило в коде, а не пожелание в промпте.

06.08 визовый бот сам предложил клиенту выбрать воскресенье, сам предложил «утро, день
или вечер» и подтвердил: «Вас записали на консультацию в воскресенье вечером». По визам
график пн–сб 10:00–19:00: в воскресенье закрыто, и «вечера» не существует ни в один день.

Причина не в формулировке. График подставлялся в знания строкой («часы работы: пн–сб
10:00–19:00»), а что из неё следует, решала модель — и решала по-разному: в ночь на 07.08
тот же бот дважды ответил правильно, а сутками раньше записал на закрытый день. Один
вопрос, разные ответы — значит правила нет, есть пожелание.

Здесь график становится вычислимым: код знает, открыто ли сейчас, какие ближайшие дни
допустимы, и умеет заметить нарушение в уже написанном ответе.

Гейт: `tests/test_office_schedule.py`.
"""
from __future__ import annotations

import re
from datetime import date, datetime, timedelta

# Решение владельца 09.08: РАЗГОВОР (звонок, онлайн-консультация) можно в любой день —
# бот и так работает ночью. А ВИЗИТ в офис, когда человек должен приехать, — только
# пн–сб; суббота считается рабочей, воскресенье закрыто на обоих направлениях.
# Часы разные: визы с 10:00 (Гриша), туры с 09:00 (Адеми), закрываются оба в 19:00.
VISIT_DAYS = {0, 1, 2, 3, 4, 5}          # понедельник–суббота

TOURS_SCHEDULE = {"days": VISIT_DAYS, "open": 9, "close": 19}
VISA_SCHEDULE = {"days": VISIT_DAYS, "open": 10, "close": 19}

_BY_BOT = {
    "getvisa": VISA_SCHEDULE,
    "getvisa_tg": VISA_SCHEDULE,
}

_RU_WEEKDAYS = ("понедельник", "вторник", "среда", "четверг", "пятница",
                "суббота", "воскресенье")

# Основы названий дней — чтобы ловить любые падежи («в воскресенье», «воскресеньем»).
_WEEKDAY_STEMS = ("понедельник", "вторник", "сред", "четверг", "пятниц",
                  "суббот", "воскресень")

# Слова, по которым видно, что человек должен ПРИЕХАТЬ. Именно визит ограничен днями:
# разговор и онлайн-консультацию владелец разрешил в любой день, и глушить их нельзя —
# бот работает ночами, и созвон в воскресенье это нормальная договорённость.
_VISIT_WORDS = ("офис", "прийт", "придт", "подойд", "подъед", "приезж", "приед",
                "ждём вас", "ждем вас", "жду вас", "заходите", "тоголок молдо", "адрес")

# Слова, по которым видно, что бот ПРАВИЛЬНО объясняет закрытый день. Кыргызский здесь
# обязателен: половина клиентов пишет на нём, и замер поймал ложное срабатывание на
# «Бүгүн (воскресенье) жабык» — бот отвечал верно, а детектор считал это ошибкой.
_REFUSAL_WORDS = ("выходной", "выходные", "не работа", "закрыт",
                  "жабык", "иштебей", "дем алыш")

# Только с двоеточием. С точкой сюда попадали даты: «вылет 05.08» разбирался как 05:08.
_TIME_RE = re.compile(r"\b([01]?\d|2[0-3]):([0-5]\d)\b")

# Диапазон часов работы («с 10:00 до 19:00», «09:00–19:00») — это НЕ предложенное время,
# а граница. Самый частый ложный из замера: бот верно называет график.
_RANGE_RE = re.compile(r"\b[0-2]?\d:[0-5]\d\s*(?:-|–|—|до)\s*[0-2]?\d:[0-5]\d\b")

# Время считаем предложением встречи, только если рядом есть слова записи. Иначе под
# детектор попадали времена рейсов: «один в 13:40, второй в 19:10».
_APPOINTMENT_WORDS = ("запис", "ждём", "ждем", "жду ", "во сколько", "к скольки",
                      "приход", "прийт", "придт", "подойд", "подъед", "приезж")

_EVENING_WORDS = ("вечером", "вечер,", "вечера", "ближе к вечеру")


def schedule_for(bot_id: str) -> dict:
    """График канала. Незнакомый бот считаем туровым — это самый широкий режим,
    и он не запрещает ничего, что раньше было разрешено."""
    return _BY_BOT.get(bot_id, TOURS_SCHEDULE)


def is_open(bot_id: str, moment: datetime) -> bool:
    """Открыт ли офис этого канала в указанный МЕСТНЫЙ момент (время Бишкека)."""
    plan = schedule_for(bot_id)
    if moment.weekday() not in plan["days"]:
        return False
    return plan["open"] <= moment.hour < plan["close"]


def next_open_days(bot_id: str, moment: datetime, count: int = 2) -> list[date]:
    """Ближайшие рабочие дни, начиная с сегодняшнего, если он ещё не кончился."""
    plan = schedule_for(bot_id)
    days: list[date] = []
    day = moment.date()
    # Сегодня годится, только если рабочий день ещё не закрылся.
    if moment.hour >= plan["close"]:
        day += timedelta(days=1)
    for _ in range(14):
        if len(days) >= count:
            break
        if day.weekday() in plan["days"]:
            days.append(day)
        day += timedelta(days=1)
    return days


def schedule_note(bot_id: str, moment: datetime) -> str:
    """Служебная заметка в промпт на каждый ход — рядом с датой.

    Дату мы так уже чинили в июле: пока её не начали подставлять вычисленной, модель
    угадывала месяц. С графиком та же болезнь и то же лекарство.
    """
    plan = schedule_for(bot_id)
    today = _RU_WEEKDAYS[moment.weekday()]
    working = "рабочий день" if moment.weekday() in plan["days"] else "ВЫХОДНОЙ"
    allowed = ", ".join(f"{d:%d.%m} ({_RU_WEEKDAYS[d.weekday()]})"
                        for d in next_open_days(bot_id, moment, count=3))
    closed = [name for i, name in enumerate(_RU_WEEKDAYS) if i not in plan["days"]]
    closed_line = (f"Выходные дни: {', '.join(closed)}. " if closed
                   else "Работаем без выходных. ")
    return (f"[Служебная заметка: сегодня {today}, для этого канала это {working}. "
            f"Часы приёма: {plan['open']:02d}:00–{plan['close']:02d}:00. {closed_line}"
            f"НИКОГДА не предлагай и не подтверждай запись в выходной день или на время "
            f"вне этих часов — «вечер» после {plan['close']:02d}:00 не существует. "
            f"Ближайшие дни, которые можно предлагать: {allowed}.]")


def violates_schedule(bot_id: str, text: str, moment: datetime) -> str:
    """Нарушает ли уже написанный ответ график. Возвращает причину или пустую строку.

    Ограничение — на ВИЗИТ, а не на разговор: владелец разрешил созвон и онлайн-консультацию
    в любой день, и глушить их нельзя. Поэтому смотрим только сообщения, где человек должен
    приехать. И не трогаем те, где бот САМ объясняет, что день выходной, — это желаемое
    поведение, а не ошибка.
    """
    if not text:
        return ""
    low = text.lower()
    if not any(word in low for word in _VISIT_WORDS):
        return ""
    if any(word in low for word in _REFUSAL_WORDS):
        return ""

    plan = schedule_for(bot_id)

    for index, stem in enumerate(_WEEKDAY_STEMS):
        if stem in low and index not in plan["days"]:
            return f"предложен выходной день: {_RU_WEEKDAYS[index]}"

    if any(word in low for word in _EVENING_WORDS):
        return f"предложен «вечер», а приём до {plan['close']:02d}:00"

    # Часы проверяем только там, где явно назначают встречу, и вырезав диапазоны графика.
    if any(word in low for word in _APPOINTMENT_WORDS):
        without_ranges = _RANGE_RE.sub(" ", text)
        for hours, minutes in _TIME_RE.findall(without_ranges):
            hour = int(hours)
            if hour < plan["open"] or hour >= plan["close"]:
                return (f"названо время {hour:02d}:{minutes} вне приёма "
                        f"{plan['open']:02d}:00–{plan['close']:02d}:00")

    return ""
