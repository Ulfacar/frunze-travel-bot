"""Фактические сборы за электронную визу в Кыргызстан — то, что клиент платит на портале.

Источник: письменный ответ Марселя от 13.11.2026 на «Вопросы по визам» от 05.11.2026,
пункты 16 и 17 (переслан Аланом 19.11.2026). Это закрывает приложение Г п.2 ТЗ v1.1
для четырёх строк ниже и только для них.

Почему отдельный модуль, а не правка базы знаний. `docs/kb-visa-inbound-v1.1-derived.md`
— конверсия PDF, её sha256 прибит в `app/knowledge/retrieval.py` (`MARKDOWN_HASH`), а на
тексте кусков стоят подписи одобрения. Вписать сюда суммы значило бы сломать поиск и
снять подписи. К тому же блок 12 в PDF — ставки постановления БЕЗ комиссии банка, а
здесь суммы С комиссией: это разные числа с разным происхождением, и смешивать их в
одном файле нельзя.

Сверка с PDF (блок 12.2, стр. 56–57): Марсель называет на 3–4% больше ставки — это
комиссия банка, которую PDF держал под [ПРОВЕРИТЬ] (оценка ≈2.9%).

    виза                  ставка PDF      факт, Марсель
    туристическая 30 дн   $50 / $150      $52 / $155
    деловая 1 месяц       $50 / $150      $52 / $155
    деловая 2 месяца      $75 / $225      $78 / $232
    деловая 3 месяца      $90 / $270      $93 / $279

Чего здесь НЕТ, и бот этого не говорит:

- кратности. Марсель не написал, однократная это виза или многократная; по PDF $50 —
  однократная, $60 — многократная. Слово «однократная» в ответ не ставим;
- остальных типов виз (студенческая, рабочая, транзитная, выездная, семейная) —
  фактических сумм по ним никто не называл;
- цены наших услуг по въезду: её в ответах нет;
- льготы швейной отрасли: по ответу Марселя она не продлена.

Модуль ничего не решает про то, НУЖНА ли клиенту виза: это делает движок режима въезда.
Поэтому ответ начинается с оговорки «если виза нужна» — гражданину безвизовой страны
названный сбор не должен читаться как «вам платить».
"""
from __future__ import annotations

import re

from app.core.lang import looks_english

CONFIRMED_ON = "2026-11-13"
CONFIRMED_BY = "Марсель"

# (тип, срок в месяцах, стандарт USD, срочно USD)
FEES: tuple[tuple[str, int, int, int], ...] = (
    ("tourist", 1, 52, 155),
    ("business", 1, 52, 155),
    ("business", 2, 78, 232),
    ("business", 3, 93, 279),
)
STANDARD_WORKING_DAYS = 5
URGENT_WORKING_DAYS = 2

# Вопрос именно о цене. Голое «сколько» сюда не входит намеренно: «сколько дней можно
# находиться» — вопрос о сроке, и выездной прайс на этом уже ошибается.
_PRICE = re.compile(
    r"сколько\s+(?:\w+\s+){0,3}сто[ия]|стоимост|\bцен[аыуе]\b|прайс|\bпоч[её]м\b|"
    r"\bсбор(?:а|ы|ов|у)?\b(?!\s+документ)|"
    r"how\s+much|\bprices?\b|\bcosts?\b|\bfees?\b",
    re.IGNORECASE)
_VISA = re.compile(r"виз|visa", re.IGNORECASE)
# Темы, по которым подтверждённых сумм нет: штрафы и просрочка, работа и Единое
# разрешение, учёба, транзит, продление, регистрация, вид на жительство, наши услуги;
# сроки и кратность вне таблицы (полгода, год, «многократная»); вопрос за другого
# человека (ребёнок, супруг — льготы и отдельные ставки нам не подтверждали).
_OUT_OF_SCOPE = re.compile(
    r"штраф|просроч|нарушен|депорт|выдвор|разрешени|работ|рабоч|трудо|уч[её]б|студен|"
    r"транзит|продл|регистрац|вид\s+на\s+жительств|резидент|семь|семей|реб[её]н|дет[еяьс]|"
    r"\bжен[аеуыо]|\bмуж|супруг|услуг|сопровожден|помощ|комисси|"
    r"\bгод|полгод|\b(?:[4-9]|1[0-2])\s*(?:-?х?\s*)?мес|шест\w*\s+мес|многократ|"
    r"однократ|мульти|"
    r"fine|penalt|overstay|permit|work|employ|stud(?:y|ent)|transit|exten|registr|"
    r"residen|family|child|kid|\bson\b|daughter|wife|husband|spouse|"
    r"your\s+(?:service|fee|price|cost|help|commission)|agency|commission|"
    r"year|annual|\b(?:[4-9]|1[0-2])\s*months?|\bsix\s+months?|multi|single",
    re.IGNORECASE)
# Другая страна назначения. Режим въездной ветки липкий, и английское «how much is a
# visa to Turkey» детектор направления оставляет в ней: без этого списка клиент,
# спросивший про Турцию, получил бы сбор за кыргызскую визу (ревью 19.11.2026).
# Список заведомо шире нужного: упоминание любой другой страны, даже как гражданства
# («я из России»), снимает ответ — ход идёт обычным путём, где суммы не называются.
_OTHER_COUNTRY = re.compile(
    r"турци|турец|дуба|оаэ|эмират|\bсша\b|америк|штат|шенген|европ|кита|коре|япони|"
    r"канад|британ|англи|росси|казахстан|узбекистан|таджикистан|герман|франц|итал|"
    r"испан|польш|turk|dubai|\buae\b|emirat|\busa?\b|america|states|schengen|europ|"
    r"chin|korea|japan|canad|brit|\buk\b|england|russia|kazakh|uzbek|tajik|german|"
    r"franc|ital|spain|poland",
    re.IGNORECASE)

REPLY_RU = (
    "Если по вашему гражданству виза нужна — государственный сбор за электронную визу "
    "с комиссией банка: туристическая на 30 дней — 52$ при обычном рассмотрении "
    f"({STANDARD_WORKING_DAYS} рабочих дней) или 155$ при срочном "
    f"({URGENT_WORKING_DAYS} рабочих дня). Деловая: на 1 месяц — 52$ / 155$, на 2 месяца "
    "— 78$ / 232$, на 3 месяца — 93$ / 279$. Сбор оплачивается на портале и при отказе "
    "не возвращается. Нужна ли виза именно вам и итог по вашему случаю подтвердит "
    "специалист."
)
REPLY_EN = (
    "If your citizenship requires a visa, the government fee for an e-visa including "
    "the bank commission is: tourist, 30 days — $52 for standard processing "
    f"({STANDARD_WORKING_DAYS} working days) or $155 for urgent processing "
    f"({URGENT_WORKING_DAYS} working days). Business: 1 month — $52 / $155, 2 months — "
    "$78 / $232, 3 months — $93 / $279. The fee is paid on the portal and is not "
    "refunded if the visa is refused. A specialist will confirm whether you need a visa "
    "and the total for your case."
)


def entry_fee_reply(text: str) -> str | None:
    """Ответ о сборе за e-Visa или None, если это не вопрос о цене визы в рамках таблицы.

    None при любом сомнении: тогда ход идёт обычным путём, где бот сумм не называет и
    передаёт вопрос специалисту.
    """
    body = text or ""
    if not _PRICE.search(body) or not _VISA.search(body):
        return None
    if _OUT_OF_SCOPE.search(body) or _OTHER_COUNTRY.search(body):
        return None
    return REPLY_EN if looks_english(body) else REPLY_RU
